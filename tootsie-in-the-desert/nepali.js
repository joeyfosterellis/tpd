// Devanagari → Brahmi, letter by letter.
window.devaToBrahmi = (function () {
  const m = {};
  const run = (from, to, n) => { for (let i = 0; i < n; i++) m[from + i] = to + i; };
  run(0x0905, 0x11005, 6);          // अ आ इ ई उ ऊ
  m[0x090B] = 0x1100B;              // ऋ
  m[0x090F] = 0x1100F; m[0x0910] = 0x11010; m[0x0913] = 0x11011; m[0x0914] = 0x11012; m[0x0911] = 0x11011;
  run(0x0915, 0x11013, 20);         // क … न
  run(0x092A, 0x11027, 7);          // प … र
  m[0x0932] = 0x1102E; m[0x0933] = 0x11034; m[0x0935] = 0x1102F;
  m[0x0936] = 0x11030; m[0x0937] = 0x11031; m[0x0938] = 0x11032; m[0x0939] = 0x11033;
  m[0x093E] = 0x11038; m[0x093F] = 0x1103A; m[0x0940] = 0x1103B; m[0x0941] = 0x1103C; m[0x0942] = 0x1103D;
  m[0x0943] = 0x1103E; m[0x0947] = 0x11042; m[0x0948] = 0x11043; m[0x094B] = 0x11044; m[0x094C] = 0x11045;
  m[0x0949] = 0x11044; m[0x0945] = 0x11042;
  m[0x094D] = 0x11046; m[0x0901] = 0x11000; m[0x0902] = 0x11001; m[0x0903] = 0x11002;
  run(0x0966, 0x11066, 10);         // digits
  return function (s) {
    let out = '';
    for (const ch of s) {
      const cp = ch.codePointAt(0);
      if (cp === 0x093C || cp === 0x200D || cp === 0x200C) continue; // nukta, joiners
      out += m[cp] ? String.fromCodePoint(m[cp]) : ch;
    }
    return out;
  };
})();
